-- 约定：本表由 load_to_mysql.py --init 一次性建表（init 只跑一次）；用 CREATE ... IF NOT EXISTS，勿加回 DROP TABLE（会清空真实库数据）。
CREATE TABLE IF NOT EXISTS telecom_operating
(
    company_code                     CHAR(10)       NOT NULL COMMENT '公司code(→company.company_code)；hk.00941 是中国移动港股年报序列,与 sh.600941 不拼接',
    fiscal_year                      SMALLINT       NOT NULL COMMENT '报告期(年度)',
    mobile_users                     DECIMAL(20, 0) NULL COMMENT '移动客户数(户,期末；原文百万户或亿户)',
    mobile_net_additions             DECIMAL(20, 0) NULL COMMENT '移动客户全年净增(户,可为负)',
    users_3g                         DECIMAL(20, 0) NULL COMMENT '3G 客户数(户)',
    users_4g                         DECIMAL(20, 0) NULL COMMENT '4G 客户数(户)',
    users_5g_network                 DECIMAL(20, 0) NULL COMMENT '5G 网络客户数(户),与 5G 套餐客户不是同一指标,不拼成一条序列',
    users_5g_package                 DECIMAL(20, 0) NULL COMMENT '5G 套餐客户数(户)',
    penetration_5g                   DECIMAL(12, 4) NULL COMMENT '5G 渗透率%(电信、联通 2023 年起只披露渗透率)',
    broadband_users                  DECIMAL(20, 0) NULL COMMENT '宽带客户数(户)；中国移动 2025 年改为宽带联网客户,与 2024 年及以前不同口径',
    home_broadband_users             DECIMAL(20, 0) NULL COMMENT '家庭宽带客户数(户)',
    gigabit_broadband_users          DECIMAL(20, 0) NULL COMMENT '千兆宽带客户数(户)',
    government_enterprise_customers  DECIMAL(20, 0) NULL COMMENT '政企客户数(户)',
    iot_connections                  DECIMAL(20, 0) NULL COMMENT '物联网卡连接数(个)',
    mobile_arpu                      DECIMAL(12, 4) NULL COMMENT '移动 ARPU(元/户/月)',
    broadband_arpu                   DECIMAL(12, 4) NULL COMMENT '宽带 ARPU(元/户/月)；三家口径不同(移动=有线宽带、电信=宽带综合、联通=接入),只比各自趋势',
    home_arpu                        DECIMAL(12, 4) NULL COMMENT '家庭客户综合 ARPU(元/户/月)',
    minutes_of_usage                 DECIMAL(12, 4) NULL COMMENT 'MOU 平均每月每户通话分钟(分钟)',
    data_of_usage                    DECIMAL(12, 4) NULL COMMENT 'DOU 平均每月每户手机上网流量(GB,早年 MB 按 1024 折算)',
    total_minutes                    DECIMAL(24, 0) NULL COMMENT '全年总通话分钟数(分钟)',
    sms_volume                       DECIMAL(24, 0) NULL COMMENT '全年短信使用量(条)',
    total_data_traffic               DECIMAL(20, 4) NULL COMMENT '全年移动数据流量(PB)',
    value_added_services_share       DECIMAL(12, 4) NULL COMMENT '增值或数据业务收入占营运收入%',
    base_stations                    DECIMAL(20, 0) NULL COMMENT '移动基站总数(个,早年口径)',
    base_stations_5g                 DECIMAL(20, 0) NULL COMMENT '5G 基站累计开通数(个,原文万站)',
    idc_racks                        DECIMAL(20, 0) NULL COMMENT '对外服务 IDC 标准机架(架,按单机架 2.5KW 折合)',
    employees                        DECIMAL(20, 0) NULL COMMENT '员工人数(人)',
    employees_approximate            TINYINT(1)     NULL COMMENT '1=员工数为年报约数(如约 45 万人)',
    capital_expenditure              DECIMAL(28, 4) NULL COMMENT '年报披露的当年资本开支(元,原文亿元),与财务接口按现金流口径的 capex 不同,两者都保留',
    capital_expenditure_guidance     DECIMAL(28, 4) NULL COMMENT '年报给出的下一年资本开支指引(元)',
    service_revenue                  DECIMAL(28, 4) NULL COMMENT '通信服务收入(元)',
    cloud_revenue                    DECIMAL(28, 4) NULL COMMENT '云业务收入(元)',
    cloud_business_name              VARCHAR(32)    NULL COMMENT '云业务名称(移动云/天翼云/联通云)',
    digital_transformation_revenue   DECIMAL(28, 4) NULL COMMENT '第二曲线收入(元)：移动=数字化转型收入、电信=产业数字化收入、联通=算网数智收入,覆盖范围不同',
    digital_transformation_name      VARCHAR(32)    NULL COMMENT '该年年报对第二曲线收入的叫法',
    depreciation_and_amortization    DECIMAL(28, 4) NULL COMMENT '年报正文披露的折旧及摊销(元)',
    approximate_fields               VARCHAR(255)   NULL COMMENT '年报以约、超过表述的近似值字段(JSON 原字段名,逗号分隔)',
    report_basis                     VARCHAR(16)    NULL COMMENT '数据取自 港股年报/A股年报(仅 hk.00941 序列有)',
    source                           VARCHAR(255)   NULL COMMENT '出处(年报文件与章节原文)',
    note                             TEXT           NULL COMMENT '该年说明原文',
    restatement_note                 TEXT           NULL COMMENT '后续年报重述说明原文(本表取当年原披露数)',
    PRIMARY KEY (company_code, fiscal_year),
    CONSTRAINT fk_telecom_operating_company FOREIGN KEY (company_code) REFERENCES company (company_code)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT ='电信运营商经营指标（telecom_ops_manual.json 三家 A 股年报 + telecom_00941_operating.json 中国移动港股年报序列,均为年报正文人工摘录）：客户数统一为户、金额统一为元,只做单位缩放；未披露为 NULL,不估算不反推；跨公司横比前先看 data_note 的口径说明';
