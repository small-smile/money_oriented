-- 约定：本表由 load_to_mysql.py --init 一次性建表（init 只跑一次）；用 CREATE ... IF NOT EXISTS，勿加回 DROP TABLE（会清空真实库数据）。
CREATE TABLE IF NOT EXISTS bank_operating
(
    company_code                                CHAR(10)       NOT NULL COMMENT '公司code(→company.company_code)',
    fiscal_year                                 SMALLINT       NOT NULL COMMENT '报告期(年度)',
    -- 零售金融
    private_banking_customers                   DECIMAL(20, 0) NULL COMMENT '私人银行客户(户,期末)：门槛各行不同,招行为月日均全折人民币总资产 1,000 万元及以上',
    wealth_product_customers                    DECIMAL(20, 0) NULL COMMENT '财富产品持仓客户(户,期末)',
    credit_cards_in_circulation                 DECIMAL(20, 0) NULL COMMENT '信用卡流通卡(张,期末)',
    credit_card_accounts_in_circulation         DECIMAL(20, 0) NULL COMMENT '信用卡流通户(户,期末)',
    credit_card_transaction_amount              DECIMAL(28, 4) NULL COMMENT '信用卡交易额(元,全年)',
    credit_card_interest_income                 DECIMAL(28, 4) NULL COMMENT '信用卡利息收入(元)',
    credit_card_non_interest_income             DECIMAL(28, 4) NULL COMMENT '信用卡非利息收入(元)',
    retail_loans                                DECIMAL(28, 4) NULL COMMENT '零售贷款余额(元,期末)：业务回顾口径,招行为本公司,与 bank_financials.retail_loans(本集团)不同,不拼接',
    retail_loans_excluding_credit_cards         DECIMAL(28, 4) NULL COMMENT '零售贷款(不含信用卡)余额(元,期末,口径同 retail_loans)',
    -- 批发金融
    corporate_customers                         DECIMAL(20, 0) NULL COMMENT '公司客户总数(户,期末)',
    new_corporate_customers                     DECIMAL(20, 0) NULL COMMENT '公司客户全年新开户(户)',
    corporate_deposit_average_balance           DECIMAL(28, 4) NULL COMMENT '公司客户存款日均余额(元)',
    corporate_wealth_management_average_balance DECIMAL(28, 4) NULL COMMENT '企业财富管理产品日均余额(元)',
    corporate_financing_total                   DECIMAL(28, 4) NULL COMMENT '公司客户融资总量(元,期末)：招行 FPA=传统融资+非传统融资,口径调整后的上年重述数记在上年那行的 restatement_note',
    traditional_financing                       DECIMAL(28, 4) NULL COMMENT '传统融资余额(元,期末)：对公一般性贷款与商票贴现、承兑、信用证、融资性与非融资性保函',
    non_traditional_financing                   DECIMAL(28, 4) NULL COMMENT '非传统融资余额(元,期末)：资产经营、自营非标、融资性理财、主承销债务融资工具、撮合交易、融资租赁、跨境联动融资、牵头银团贷款',
    corporate_collection_payment_customers      DECIMAL(20, 0) NULL COMMENT '对公代扣代缴交易客户(户,全年)',
    corporate_collection_payment_amount         DECIMAL(28, 4) NULL COMMENT '对公代扣代缴交易金额(元,全年)',
    -- 同业、资管与托管
    interbank_deposit_average_balance           DECIMAL(28, 4) NULL COMMENT '同业存款日均余额(元)',
    interbank_demand_deposit_share              DECIMAL(12, 4) NULL COMMENT '同业活期存款占同业存款%(日均)',
    third_party_depository_brokers              INT            NULL COMMENT '证券第三方存管合作券商(家)',
    third_party_depository_customers            DECIMAL(20, 0) NULL COMMENT '证券第三方存管客户(户,期末)',
    bank_futures_transfer_firms                 INT            NULL COMMENT '银期转账合作期货公司(家)',
    bank_futures_transfer_customers             DECIMAL(20, 0) NULL COMMENT '银期转账客户(户,期末)',
    asset_management_total                      DECIMAL(28, 4) NULL COMMENT '资管业务总规模(元,期末)：含哪些子公司与产品照各行原文',
    custody_assets                              DECIMAL(28, 4) NULL COMMENT '托管资产余额(元,期末)',
    -- 渠道
    mobile_banking_app_monthly_active_users     DECIMAL(20, 0) NULL COMMENT '手机银行 App 月活跃用户(户)：招行为招商银行 App',
    credit_card_app_monthly_active_users        DECIMAL(20, 0) NULL COMMENT '信用卡 App 月活跃用户(户)：招行为掌上生活 App',
    wholesale_online_customers                  DECIMAL(20, 0) NULL COMMENT '批发线上渠道客户(户,期末)',
    wholesale_online_customer_coverage          DECIMAL(12, 4) NULL COMMENT '批发线上渠道客户覆盖率%',
    wholesale_online_monthly_active_customers   DECIMAL(20, 0) NULL COMMENT '批发线上渠道月活跃客户(户)',
    wholesale_online_transactions               DECIMAL(20, 0) NULL COMMENT '批发线上渠道交易笔数(笔,全年)',
    wholesale_online_transaction_amount         DECIMAL(28, 4) NULL COMMENT '批发线上渠道交易金额(元,全年)',
    domestic_branches                           INT            NULL COMMENT '境内分行(家,期末)',
    domestic_sub_branches                       INT            NULL COMMENT '境内支行(家,期末)',
    branch_level_specialized_institutions       INT            NULL COMMENT '分行级专营机构(家,期末)：招行为信用卡中心、资金营运中心',
    self_service_banks                          INT            NULL COMMENT '自助银行(家,期末)',
    self_service_devices                        INT            NULL COMMENT '自助设备(台,期末)',
    video_devices                               INT            NULL COMMENT '可视设备(台,期末)',
    net_new_outlets                             INT            NULL COMMENT '全年净增营业网点(家,可为负)',
    relocated_outlets                           INT            NULL COMMENT '全年迁址优化的存量营业网点(家)',
    source                                      VARCHAR(255)   NULL COMMENT '出处(年报文件、章节、页码)',
    note                                        TEXT           NULL COMMENT '该年口径说明原文',
    restatement_note                            TEXT           NULL COMMENT '后续年报重述说明原文(本表取当年原披露数)',
    PRIMARY KEY (company_code, fiscal_year),
    CONSTRAINT fk_bank_operating_company FOREIGN KEY (company_code) REFERENCES company (company_code)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT ='银行经营指标（年报「管理层讨论与分析」业务回顾的人工摘录）：客户数统一为户、卡为张、笔数为笔、金额为元,只做单位缩放(原文万户、亿元、万亿元)；多为本公司(母行)口径,与 bank_financials 的本集团口径不拼接,每家每年的口径写进 note；未披露为 NULL,不估算不反推；利息收支与资产质量这类财务指标在 bank_financials,按分项拆的(企业规模、产品类别、业务条线)在 bank_report_detail';