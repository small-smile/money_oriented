-- 约定：本表由 load_to_mysql.py --init 一次性建表（init 只跑一次）；用 CREATE ... IF NOT EXISTS，勿加回 DROP TABLE（会清空真实库数据）。
CREATE TABLE IF NOT EXISTS cement_operating
(
    company_code                CHAR(10)       NOT NULL COMMENT '公司code(→company.company_code)',
    fiscal_year                 SMALLINT       NOT NULL COMMENT '报告期(年度)',
    currency                    VARCHAR(8)     NULL COMMENT '金额币种 CNY/HKD(华润水泥 01313 的 2022 年及以前为港元)；NULL=手工层该年没单列币种,按人民币',
    sales_volume_total          DECIMAL(20, 2) NULL COMMENT '水泥及熟料销量合计(吨,原文万吨)',
    cement_sales_volume         DECIMAL(20, 2) NULL COMMENT '水泥销量(吨)',
    clinker_sales_volume        DECIMAL(20, 2) NULL COMMENT '熟料销量(吨)',
    self_produced_sales_volume  DECIMAL(20, 2) NULL COMMENT '自产品销量(吨,海螺 2017 年起的口径,另有贸易量)',
    trading_volume              DECIMAL(20, 2) NULL COMMENT '贸易量(吨)',
    aggregate_sales_volume      DECIMAL(20, 2) NULL COMMENT '骨料销量(吨)',
    concrete_sales_volume       DECIMAL(20, 2) NULL COMMENT '混凝土销量(立方米,原文万立方米)',
    cement_production_volume    DECIMAL(20, 2) NULL COMMENT '水泥产量(吨)',
    clinker_production_volume   DECIMAL(20, 2) NULL COMMENT '熟料产量(吨)',
    cement_revenue              DECIMAL(28, 4) NULL COMMENT '水泥收入(元,原文百万元)',
    cement_cost                 DECIMAL(28, 4) NULL COMMENT '水泥成本(元)',
    cement_gross_margin         DECIMAL(12, 4) NULL COMMENT '水泥毛利率%',
    self_produced_revenue       DECIMAL(28, 4) NULL COMMENT '自产品收入(元,剔除贸易)',
    self_produced_cost          DECIMAL(28, 4) NULL COMMENT '自产品成本(元)',
    self_produced_gross_margin  DECIMAL(12, 4) NULL COMMENT '自产品毛利率%',
    total_line_revenue          DECIMAL(28, 4) NULL COMMENT '分行业合计行收入(元,水泥及熟料合计,年报未单列自产品时用,可能含少量贸易)',
    total_line_cost             DECIMAL(28, 4) NULL COMMENT '分行业合计行成本(元)',
    total_line_gross_margin     DECIMAL(12, 4) NULL COMMENT '分行业合计行毛利率%',
    aggregate_revenue           DECIMAL(28, 4) NULL COMMENT '骨料收入(元)',
    aggregate_cost              DECIMAL(28, 4) NULL COMMENT '骨料成本(元)',
    concrete_revenue            DECIMAL(28, 4) NULL COMMENT '混凝土收入(元)',
    concrete_cost               DECIMAL(28, 4) NULL COMMENT '混凝土成本(元)',
    unit_cost_disclosed         DECIMAL(12, 4) NULL COMMENT '年报直接披露的吨成本(元/吨,港元年份为港元/吨),与收入成本÷销量的自算值口径不同,不混用',
    unit_price_disclosed        DECIMAL(12, 4) NULL COMMENT '年报直接披露的吨售价(元/吨)',
    unit_gross_profit_disclosed DECIMAL(12, 4) NULL COMMENT '年报直接披露的吨毛利(元/吨)',
    source_page                 VARCHAR(64)    NULL COMMENT '年报页码(原文,多页逗号分隔)',
    note                        TEXT           NULL COMMENT '该年的口径说明原文(重述、行项目取舍等)',
    source                      VARCHAR(255)   NULL COMMENT '来源文件',
    PRIMARY KEY (company_code, fiscal_year),
    CONSTRAINT fk_cement_operating_company FOREIGN KEY (company_code) REFERENCES company (company_code)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT ='水泥经营口径（cement_ops_manual.json,逐份年报语义通读人工摘录）：只取年报披露的销量,不倒算、不把产量当销量,每年取当年年报本期数不用重述数,未披露为 NULL；吨收入/吨成本由后端按各家 unit_rule 现算不入库,各家口径规则见 data_note';
