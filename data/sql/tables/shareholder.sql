-- 约定：本表由 load_to_mysql.py --init 一次性建表（init 只跑一次）；用 CREATE ... IF NOT EXISTS，勿加回 DROP TABLE（会清空真实库数据）。
CREATE TABLE IF NOT EXISTS shareholder
( -- 某一期 top 股东明细表；A+H 的数据源从 A 出
    id            BIGINT       NOT NULL AUTO_INCREMENT,
    company_code  CHAR(10)     NOT NULL COMMENT '公司code(→company.company_code)',
    fiscal_year   SMALLINT     NOT NULL COMMENT '报告期(年度)',
    as_of_date    DATE         NULL COMMENT '名册截止日：年报为 12-31,20-F 等年报披露日在次年 1–4 月的记上一年度(如百度 2026-01-31 记 2025)',
    holder_rank   SMALLINT     NULL COMMENT '名次(前十名股东表顺序)',
    holder_name   VARCHAR(128) NOT NULL COMMENT '股东名称',
    holder_short  VARCHAR(64) NULL COMMENT '股东名称(短)：年报页面上的简称(如 渝富资本),一致行动人表用简称时靠它对回名册全称(holders_manual.json 的 faction_aliases、银行股东手工件的 top10)',
    holder_category VARCHAR(8) NULL COMMENT '年报口径股东页的股东分类(环形图配色)：soe=国有股东/hk=境外/H股/ssf=社保基金/ins=保险资金/corp=内资法人/other=其他；银行股东手工件(bank_<code>_shareholder_manual.json 的 top10)给了才填,其余由页面按名称关键词归类',
    concert_party VARCHAR(128) NULL COMMENT '一致行动人',
    concert_short VARCHAR(64) NULL COMMENT '一致行动人(短)',
    is_state      TINYINT(1)    NULL COMMENT '是否国资(国有)；按 holder_nature 推出,性质说明不了时留空(其他/未知、境外法人、内资法人股、未披露性质)',
    is_foreign    TINYINT(1)    NULL COMMENT '是否外资(境外股东)；按 holder_nature 推出,性质为其他/未知或未披露时留空',
    is_natural    TINYINT(1)    NULL COMMENT '是否自然人；按 holder_nature 推出,性质为其他/未知或未披露时留空',
    is_listed     TINYINT(1)    NULL COMMENT '是否上市',
    holder_nature VARCHAR(32)  NULL COMMENT '股东/股份性质原文(国有法人/境内自然人/国有法人股…)；is_state/is_foreign/is_natural 按本列推出,对照见 load_to_mysql.py 的 HOLDER_NATURE_FLAGS',
    hold_num      BIGINT NULL COMMENT '期末持股数(股)',
    ratio         DECIMAL(10, 4) NULL COMMENT '期末持股比例%',
    total_shares  BIGINT       NULL COMMENT '名册所列总股本(股),持股比例的分母',
    shares_type   VARCHAR(16) NULL COMMENT '股份类别 A/H/A,H(两类都持有)/非上市股',
    raw_shares_type VARCHAR(255) NULL COMMENT '股份类别或性质原文,页面照原文显示：接口为 流通A股、限售流通A股,流通H股 等,年报手工件写股东性质,20-F 写股份类别说明',
    pledged_shares BIGINT      NULL COMMENT '质押或冻结股数(股)',
    chg_shares    BIGINT NULL COMMENT '报告期内股本变动(股)',
    raw_change    VARCHAR(32)  NULL COMMENT '增减原文：来源写成文字的照存(不变/新进/未知,或写成字符串的股数)；来源本身是数值的只进 chg_shares,本列为空',
    chg_ratio     DECIMAL(10, 4) NULL COMMENT '报告期内股本变动(比例)',
    change_status VARCHAR(8)   NULL COMMENT '持股变动状态 新进/加仓/减仓/不变',
    raw_state     VARCHAR(32)  NULL COMMENT '接口 HOLDER_STATE 原文(新进/加仓/减仓/不变,个别公司写股份类别或性质)；年报手工件为空串',
    is_additional TINYINT(1) NULL COMMENT '是否补充股东：不在A股前十名名册、据H股≥5%主要股东权益披露补入(如Peaktrade)，1=是 ，　或者5%以上股东、控股股东、实际控制人等权益披露中的实际披露　',
    source        VARCHAR(255) NULL COMMENT '数据来源',
    PRIMARY KEY (id),
    UNIQUE KEY uk_shareholder (company_code, fiscal_year, holder_name),
    CONSTRAINT fk_shareholder_company FOREIGN KEY (company_code) REFERENCES company (company_code)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 comment='某一期的股权结构  优先使用 A 股的top 10 股东数据 ,  ';
